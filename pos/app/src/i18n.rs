#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_i18n_translations() {
        assert_eq!(
            tr(UiLang::Id, "app_title"),
            "Publication Orchestrator Studio"
        );
        assert_eq!(tr(UiLang::Id, "source_and_content"), "Sumber & Konten");
        assert_eq!(tr(UiLang::En, "source_and_content"), "Source & Content");
        assert_eq!(tr(UiLang::Id, "publication_profile"), "Profil Publikasi");
        assert_eq!(tr(UiLang::En, "publication_profile"), "Publication Profile");
    }

    #[test]
    fn all_keys_have_both_languages() {
        assert!(
            KEYS.len() >= 120,
            "expected at least 120 keys, found {}",
            KEYS.len()
        );

        let mut seen = std::collections::HashSet::new();
        for key in KEYS {
            assert!(seen.insert(*key), "duplicate key in KEYS: {key}");
            for lang in UiLang::ALL {
                let value = tr(lang, key);
                assert!(!value.is_empty(), "{key} is empty for {lang}");
                assert_ne!(value, *key, "{key} falls back to the key for {lang}");
            }
        }
    }
}
